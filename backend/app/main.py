from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from app.config import settings
from app.api import (
    dashboard_router,
    feeders_router,
    events_router,
    faults_router,
    restoration_router,
    weather_router,
    analytics_router,
)

app = FastAPI(
    title=settings.PROJECT_NAME,
    version=settings.VERSION,
    description=(
        "**FaultTrace AI** - Decision-support system for BESCOM Power Hack 2026 Theme 10 "
        "(Digital Transformation of BESCOM Distribution Operations).\n\n"
        "> **SYNTHETIC DEMO DATA NOTICE**: All data is synthetic and generated by our simulator. "
        "No access to real BESCOM infrastructure.\n"
        "> **ADVISORY NOTICE**: The system is advisory only and never executes switching directly."
    )
)

# Enable CORS for local Vite frontend
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Include Routers
app.include_router(dashboard_router, prefix=settings.API_V1_STR)
app.include_router(feeders_router, prefix=settings.API_V1_STR)
app.include_router(events_router, prefix=settings.API_V1_STR)
app.include_router(faults_router, prefix=settings.API_V1_STR)
app.include_router(restoration_router, prefix=settings.API_V1_STR)
app.include_router(weather_router, prefix=settings.API_V1_STR)
app.include_router(analytics_router, prefix=settings.API_V1_STR)

@app.get("/")
def root():
    return {
        "project": settings.PROJECT_NAME,
        "version": settings.VERSION,
        "synthetic_notice": settings.SYNTHETIC_DATA_BANNER,
        "advisory_disclaimer": settings.ADVISORY_DISCLAIMER,
        "docs_url": "/docs",
        "api_v1_prefix": settings.API_V1_STR
    }

@app.get("/health")
def health():
    return {
        "status": "healthy",
        "synthetic_data": True,
        "advisory_mode": True
    }
